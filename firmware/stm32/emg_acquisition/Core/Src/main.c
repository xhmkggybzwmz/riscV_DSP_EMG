void EMG_SPI3_TxCpltCallback(void) {
    if (emg_spi_busy) {
        HAL_GPIO_WritePin(EMG_SPI_CS_GPIO_Port, EMG_SPI_CS_Pin, GPIO_PIN_SET);
        emg_stats.sent_blocks++;
        EMG_ReleaseSlot(emg_spi_slot);
        emg_spi_slot = 0xff;
        emg_spi_busy = 0;
    }
}

void EMG_SPI3_ErrorCallback(void) {
    if (emg_spi_busy) {
        HAL_GPIO_WritePin(EMG_SPI_CS_GPIO_Port, EMG_SPI_CS_Pin, GPIO_PIN_SET);
        emg_stats.transport_errors++;
        EMG_ReleaseSlot(emg_spi_slot);
        emg_spi_slot = 0xff;
        emg_spi_busy = 0;
    }
}
