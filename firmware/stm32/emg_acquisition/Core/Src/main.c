static void put_u16_le(uint8_t *p, uint16_t value) {
    p[0] = (uint8_t)(value);
    p[1] = (uint8_t)(value >> 8);
}

static void put_u32_le(uint8_t *p, uint32_t value) {
    p[0] = (uint8_t)(value);
    p[1] = (uint8_t)(value >> 8);
    p[2] = (uint8_t)(value >> 16);
    p[3] = (uint8_t)(value >> 24);
}

static uint16_t crc16_update(
    uint16_t crc,
    const uint8_t *data,
    uint32_t length) {
    for (uint32_t i = 0; i < length; i++) {
        crc ^= ((uint16_t)data[i] << 8);

        for (uint8_t bit = 0; bit < 8; bit++) {
            if (crc & 0x8000) {
                crc = (uint16_t)((crc << 1) ^ 0x1021);
            }
            else {
                crc <<= 1;
            }
        }
    }

    return crc;
}

static void EMG_BuildFrame(
    uint8_t *frame,
    const uint16_t *samples,
    uint32_t first_sample_index)
{
    const uint16_t payload_bytes = ADC_HALF_LEN * sizeof(uint16_t);

    /* Magic: "EMG1" */
    frame[0] = 'E'; frame[1] = 'M'; frame[2] = 'G'; frame[3] = '1';

    /* Version */
    frame[4] = EMG_PROTOCOL_VERSION;

    /* Sample format */
    frame[5] = EMG_FORMAT_U16_LE;

    /* Channel count */
    frame[6] = EMG_CHANNEL_COUNT;

    /* Reserved */
    frame[7] = 0;

    /* Sample rate */
    put_u32_le(
        &frame[8],
        EMG_SAMPLE_RATE_HZ
    );

    /* Index of first sample in this packet */
    put_u32_le(
        &frame[12],
        first_sample_index
    );

    /* Samples per channel */
    put_u16_le(
        &frame[16],
        ADC_HALF_LEN
    );

    /* Payload size */
    put_u16_le(
        &frame[18],
        payload_bytes
    );

    for (uint16_t i = 0; i < ADC_HALF_LEN; ++i) {
#if EMG_SOURCE_MODE == EMG_SOURCE_TEST
        const uint16_t value = emg_test_value;
        emg_test_value = (uint16_t)((emg_test_value + 1U) & 0x0FFFU); /* 12 bits, like the ADC */
#elif EMG_SOURCE_MODE == EMG_SOURCE_REPLAY
        /* from the index, not a counter of its own: a block dropped while READY is low must not shift the recording */
        const uint16_t value = emg_replay[(first_sample_index + i) % EMG_REPLAY_N];
#else
        const uint16_t value = samples[i];
#endif
        put_u16_le(&frame[EMG_HEADER_SIZE + (uint32_t)i * 2], value);
    }

    /*
     * CRC16 over:
     * header + payload
     */
    uint16_t crc = 0xFFFF;

    crc = crc16_update(
        crc,
        frame,
        EMG_HEADER_SIZE + payload_bytes
    );
    put_u16_le(&frame[EMG_HEADER_SIZE + payload_bytes], crc);
}

static void EMG_QueueBlock(const uint16_t *samples)
{
    const uint32_t first_index = emg_capture_index;
    const uint8_t slot = emg_producer;
    emg_capture_index += ADC_HALF_LEN;
    emg_stats.captured_blocks++;
    if (emg_slot_state[slot] != SLOT_FREE) {
        emg_stats.dropped_blocks++;
        return;
    }
    EMG_BuildFrame(emg_frames[slot], samples, first_index);
    __DMB();
    emg_slot_state[slot] = SLOT_READY;
    emg_producer = (uint8_t)((slot + 1U) % EMG_QUEUE_DEPTH);
    emg_stats.queued_blocks++;
}

static void EMG_ReleaseSlot(uint8_t slot)
{
    emg_slot_state[slot] = SLOT_FREE;
    emg_consumer = (uint8_t)((slot + 1U) % EMG_QUEUE_DEPTH);
}

static void EMG_TransportPoll(void)
{
    const uint8_t slot = emg_consumer;
#if EMG_TRANSPORT_MODE == EMG_TRANSPORT_SPI
    if (emg_spi_busy) {
        if ((HAL_GetTick() - emg_spi_started_ms) > EMG_SPI_TIMEOUT_MS) {
            const uint32_t primask = __get_PRIMASK();
            __disable_irq();
            /* A completion IRQ may race the timeout test. Recheck while the
             * DMA callback cannot change emg_spi_slot underneath us. */
            if (emg_spi_busy) {
                const uint8_t timed_out_slot = emg_spi_slot;
                EMG_SPI3_Abort();
                HAL_GPIO_WritePin(EMG_SPI_CS_GPIO_Port, EMG_SPI_CS_Pin, GPIO_PIN_SET);
                emg_stats.transport_timeouts++;
                emg_stats.transport_errors++;
                emg_spi_slot = 0xff;
                emg_spi_busy = 0;
                EMG_ReleaseSlot(timed_out_slot);
            }
            if (primask == 0U) __enable_irq();
        }
        return;
    }
    if (emg_slot_state[slot] != SLOT_READY) return;
    if (HAL_GPIO_ReadPin(EMG_SPI_READY_GPIO_Port, EMG_SPI_READY_Pin) != GPIO_PIN_SET) return;
    emg_slot_state[slot] = SLOT_SENDING;
    emg_spi_slot = slot;
    emg_spi_busy = 1;
    emg_spi_started_ms = HAL_GetTick();
    HAL_GPIO_WritePin(EMG_SPI_CS_GPIO_Port, EMG_SPI_CS_Pin, GPIO_PIN_RESET);
    if (EMG_SPI3_Transmit_DMA(emg_frames[slot], EMG_FRAME_SIZE) != HAL_OK) {
        HAL_GPIO_WritePin(EMG_SPI_CS_GPIO_Port, EMG_SPI_CS_Pin, GPIO_PIN_SET);
        emg_stats.transport_errors++;
        EMG_ReleaseSlot(slot);
        emg_spi_slot = 0xff;
        emg_spi_busy = 0;
    }
#else
    if (emg_slot_state[slot] != SLOT_READY) return;
    emg_slot_state[slot] = SLOT_SENDING;
    if (HAL_UART_Transmit(&huart1, emg_frames[slot], EMG_FRAME_SIZE, 100) == HAL_OK)
        emg_stats.sent_blocks++;
    else
        emg_stats.transport_errors++;
    EMG_ReleaseSlot(slot);
#endif
}

