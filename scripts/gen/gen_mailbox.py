#!/usr/bin/env python3
"""Generate the E4a mailbox v1 constants from their single sources.

  python scripts/gen/gen_mailbox.py           # write the generated files
  python scripts/gen/gen_mailbox.py --check   # exit 1 if a generated file is out of date

Sources
  host/ps_mailbox/protocol.py   layout, magic numbers, flags, labels
  rtl/soc/soc_addr_map.vh       SOC_MBX_BASE/SIZE (CPU side), KV260_MBX_PS_BASE/SIZE (PS side)
  fpga/kv260/tcl/kv260_bd.tcl   KV260_DBG_BASE (debug window, design identity check)
  fpga/kv260/rtl/kv260_dbg_axil.v ID_VALUE
Outputs (committed, "GENERATED" banner)
  firmware/rv32/mailbox/mbx_layout.h
  dv/mbx/mbx_layout.vh
  host/ps_mailbox/configs/kv260_mailbox.json
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OUT_H = REPO / "firmware" / "rv32" / "mailbox" / "mbx_layout.h"
OUT_VH = REPO / "dv" / "mbx" / "mbx_layout.vh"
OUT_JSON = REPO / "host" / "ps_mailbox" / "configs" / "kv260_mailbox.json"


def load_protocol():
    spec = importlib.util.spec_from_file_location("mbx_protocol", REPO / "host" / "ps_mailbox" / "protocol.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def addr_map() -> dict:
    text = (REPO / "rtl" / "soc" / "soc_addr_map.vh").read_text(encoding="utf-8")
    vals = {n: int(v.replace("_", ""), 16) for n, v in re.findall(r"`define\s+(\w+)\s+32'h([0-9A-Fa-f_]+)", text)}
    bd = (REPO / "fpga" / "kv260" / "tcl" / "kv260_bd.tcl").read_text(encoding="utf-8")
    vals["KV260_DBG_BASE"] = int(re.search(r"set KV260_DBG_BASE (0x[0-9A-Fa-f]+)", bd).group(1), 16)
    dbg = (REPO / "fpga" / "kv260" / "rtl" / "kv260_dbg_axil.v").read_text(encoding="utf-8")
    vals["KV260_DBG_ID"] = int(re.search(r"ID_VALUE = 32'h([0-9A-Fa-f_]+)", dbg).group(1).replace("_", ""), 16)
    return vals


BANNER = ("GENERATED by scripts/gen/gen_mailbox.py from host/ps_mailbox/protocol.py and "
          "rtl/soc/soc_addr_map.vh. Do not edit.")


def gen_h(p, a) -> str:
    L = ["/* mbx_layout.h - E4a mailbox v1 layout (docs/soc/e4a_mailbox.md).",
         f" * {BANNER} */",
         "#ifndef MBX_LAYOUT_H", "#define MBX_LAYOUT_H", "",
         f"#define MBX_BASE           0x{a['SOC_MBX_BASE']:08X}u   /* CPU address of the mailbox window */",
         f"#define MBX_SIZE           0x{a['SOC_MBX_SIZE']:X}u",
         f"#define MBX_MAGIC          0x{p.MAGIC:08X}u",
         f"#define MBX_VERSION        0x{p.VERSION:08X}u",
         f"#define MBX_RING_SIZE      {p.RING_SIZE}u",
         f"#define MBX_RECORD_SIZE    {p.RECORD_SIZE}u",
         f"#define MBX_RING_OFFSET    0x{p.RING_OFFSET:03X}u", "",
         "/* header byte offsets (writer: cpu / ps) */"]
    for n, (off, who, d) in p.HEADER.items():
        L.append(f"#define MBX_H_{n:<20s} 0x{off:03X}u   /* {who}: {d} */")
    L += ["", "/* STATE */"]
    for v, n in p.STATE_NAMES.items():
        L.append(f"#define MBX_STATE_{n:<10s} {v}u")
    L += ["", "/* LAST_ERROR */"]
    for n in ("ERR_NONE", "ERR_BAD_CONSUMER", "ERR_CNN_CHECK", "ERR_TIMEOUT", "ERR_ARGMAX"):
        L.append(f"#define MBX_{n:<18s} {getattr(p, n)}u")
    L += ["", "/* record word indices */"]
    for n, (w, d) in p.RECORD.items():
        L.append(f"#define MBX_W_{n:<16s} {w}u   /* {d} */")
    L += ["", f"#define MBX_REC_MAGIC      0x{p.REC_MAGIC:04X}u",
          f"#define MBX_REC_VERSION    {p.REC_VERSION}u", "", "/* REC_HDR[7:0] flags */"]
    for n in ("F_POSTPROC", "F_DROP_BEFORE", "F_NEW_SEGMENT", "F_ARGMAX_OK", "F_GOLDEN_OK", "F_LAST"):
        L.append(f"#define MBX_{n:<14s} 0x{getattr(p, n):02X}u")
    L += ["", f"#define MBX_GESTURE_UNCERTAIN   ({p.GESTURE_UNCERTAIN})",
          f"#define MBX_GESTURE_NO_DECISION ({p.GESTURE_NO_DECISION})", "", "#endif", ""]
    return "\n".join(L)


def gen_vh(p, a) -> str:
    L = ["// mbx_layout.vh - E4a mailbox v1 layout for the test benches (docs/soc/e4a_mailbox.md).",
         f"// {BANNER}", "`ifndef MBX_LAYOUT_VH", "`define MBX_LAYOUT_VH",
         f"`define MBX_CPU_BASE 32'h{a['SOC_MBX_BASE']:08X}",
         f"`define MBX_PS_BASE 32'h{a['KV260_MBX_PS_BASE']:08X}",
         f"`define MBX_SIZE {a['SOC_MBX_SIZE']}",
         f"`define MBX_MAGIC 32'h{p.MAGIC:08X}",
         f"`define MBX_VERSION 32'h{p.VERSION:08X}",
         f"`define MBX_RING_SIZE {p.RING_SIZE}",
         f"`define MBX_RECORD_SIZE {p.RECORD_SIZE}",
         f"`define MBX_RING_OFFSET {p.RING_OFFSET}"]
    for n, (off, _, _) in p.HEADER.items():
        L.append(f"`define MBX_H_{n} {off}")
    for v, n in p.STATE_NAMES.items():
        L.append(f"`define MBX_STATE_{n} {v}")
    for n, (w, _) in p.RECORD.items():
        L.append(f"`define MBX_W_{n} {w}")
    L += [f"`define MBX_REC_MAGIC 16'h{p.REC_MAGIC:04X}", f"`define MBX_REC_VERSION {p.REC_VERSION}"]
    for n in ("F_POSTPROC", "F_DROP_BEFORE", "F_NEW_SEGMENT", "F_ARGMAX_OK", "F_GOLDEN_OK", "F_LAST"):
        L.append(f"`define MBX_{n} 8'h{getattr(p, n):02X}")
    L += ["`endif", ""]
    return "\n".join(L)


def gen_json(p, a) -> str:
    cfg = {
        "_comment": BANNER,
        "protocol": "mailbox v1 (docs/soc/e4a_mailbox.md)",
        "ps_base": f"0x{a['KV260_MBX_PS_BASE']:08X}",
        "window_size": a["KV260_MBX_PS_SIZE"],
        "cpu_base": f"0x{a['SOC_MBX_BASE']:08X}",
        "magic": f"0x{p.MAGIC:08X}",
        "version": f"0x{p.VERSION:08X}",
        "ring_size": p.RING_SIZE, "record_size": p.RECORD_SIZE, "ring_offset": p.RING_OFFSET,
        "header": {n: off for n, (off, _, _) in p.HEADER.items()},
        "record": {n: w for n, (w, _) in p.RECORD.items()},
        "labels": list(p.LABELS),
        "board": {
            "overlay": "rv32_6a",
            "fpga_manager": "/sys/class/fpga_manager/fpga0",
            "dbg_base": f"0x{a['KV260_DBG_BASE']:08X}",
            "dbg_id": f"0x{a['KV260_DBG_ID']:08X}",
        },
    }
    return json.dumps(cfg, indent=1) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    ns = ap.parse_args()
    p, a = load_protocol(), addr_map()
    if a["SOC_MBX_SIZE"] != p.WINDOW_SIZE or a["KV260_MBX_PS_SIZE"] != p.WINDOW_SIZE:
        sys.exit("soc_addr_map.vh mailbox sizes differ from protocol.WINDOW_SIZE")
    if p.RING_OFFSET + p.RING_SIZE * p.RECORD_SIZE > p.WINDOW_SIZE:
        sys.exit("ring does not fit the window")
    outs = {OUT_H: gen_h(p, a), OUT_VH: gen_vh(p, a), OUT_JSON: gen_json(p, a)}
    stale = []
    for f, text in outs.items():
        old = f.read_text(encoding="utf-8") if f.is_file() else None
        if old != text:
            stale.append(f)
            if not ns.check:
                f.parent.mkdir(parents=True, exist_ok=True)
                f.write_text(text, encoding="utf-8", newline="\n")
    for f in stale:
        print(f"{'STALE' if ns.check else 'wrote'} {f.relative_to(REPO).as_posix()}")
    if ns.check and stale:
        return 1
    if not stale:
        print("mailbox constants up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
