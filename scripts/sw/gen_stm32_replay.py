#!/usr/bin/env python3
"""Put part of a recording into STM32 flash so that it can reach the KV260 over SPI with nobody wired to the board.

    python scripts/sw/gen_stm32_replay.py analysis/spi/rec2.npz            # the last round (the test round of training)
    python scripts/sw/build_stm32.py                                       # then also builds build/stm32/replay

Writes build/stm32/replay_data/emg_replay.h and replay.npz (u16, label: for scripts/fpga/check_spi_replay.py). Both hold
real samples, so they stay in the ignored build/. The length is a multiple of the 128-sample block.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "build" / "stm32" / "replay_data"
FLASH_LIMIT_SAMPLES = 400_000       # 1 MB flash, the program needs little


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("rec")
    ap.add_argument("--rounds", type=int, default=1, help="how many rounds, counted from the last one")
    ns = ap.parse_args()
    z = np.load(ns.rec)
    u, label, rnd = z["u16"], z["label"], z["round"]
    keep = np.isin(rnd, sorted(set(rnd[label >= 0].tolist()))[-ns.rounds:])
    u, label = u[keep], label[keep]
    n = len(u) // 128 * 128
    if not 0 < n <= FLASH_LIMIT_SAMPLES:
        raise SystemExit(f"{n} samples do not fit")
    u, label = u[:n], label[:n]
    OUT.mkdir(parents=True, exist_ok=True)
    rows = [", ".join(str(int(v)) for v in u[i:i + 16]) for i in range(0, n, 16)]
    text = ("/* GENERATED by scripts/sw/gen_stm32_replay.py: real samples, do not commit */\n"
            f"#define EMG_REPLAY_N {n}U\n"
            f"static const uint16_t emg_replay[EMG_REPLAY_N] = {{\n" + ",\n".join(rows) + "\n};\n")
    (OUT / "emg_replay.h").write_text(text, encoding="ascii", newline="\n")
    np.savez(OUT / "replay.npz", u16=u, label=label)
    print(f"{n} samples, {n / 2000:.1f} s, labels {[int((label == c).sum()) for c in (-1, 0, 1, 2)]} -> {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
