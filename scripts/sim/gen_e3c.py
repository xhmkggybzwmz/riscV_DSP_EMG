#!/usr/bin/env python3
"""E3c inputs derived from the E2 golden vectors (no new data, no retraining).

  python scripts/sim/gen_e3c.py [--case chain_s1_normal]

Reads build/e3/vec/<case> (scripts/sim/gen_e3_vectors.py; run scripts/sim/run_e3.py
first, or this script runs the generator) and writes
  build/e3c/replay_<case>.hex       frame memory init of esi_replay_axil: one 72-bit word
                                    {flags[7:0], lane3, lane2, lane1, lane0} per frame
  build/e3c/e3c_paths.vh            `define E3C_REPLAY_FILE / E3C_REPLAY_FRAMES + the model
                                    file defines of build/e3/model_paths.vh
  firmware/rv32/e3c/e3c_expected.h  expected results for the RV32I firmware: per decision the
                                    six int32 scores, argmax, window end, segment and the frame
                                    index of the window end; the 20 DSP coefficients

The model is the frozen E2 reference fold (subject 1, P2 test day 3, seed 0).
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
VEC = REPO / "build" / "e3" / "vec"
OUT = REPO / "build" / "e3c"
HDR = REPO / "firmware" / "rv32" / "e3c" / "e3c_expected.h"


def words(path: Path) -> list[int]:
    return [int(l, 16) for l in path.read_text(encoding="ascii").split() if l.strip()]


def s32(v: int) -> int:
    v &= 0xFFFF_FFFF
    return v - (1 << 32) if v & 0x8000_0000 else v


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--case", default="chain_s1_normal")
    ns = ap.parse_args()
    d = VEC / ns.case
    if not (d / "input_frames.hex").is_file():
        subprocess.run([sys.executable, str(REPO / "scripts" / "sim" / "gen_e3_vectors.py")], check=True)
    OUT.mkdir(parents=True, exist_ok=True)

    frames = words(d / "input_frames.hex")             # {seq[31:0], flags[15:0], lanes[127:0]}
    rep = []
    for f in frames:
        lanes = f & ((1 << 64) - 1)                     # lanes 0..3
        flags = (f >> 128) & 0xFF
        if (f >> 64) & ((1 << 64) - 1):
            sys.exit("lanes 4..7 are not zero: the replay stores 4 channels")
        rep.append((flags << 64) | lanes)
    rfile = OUT / f"replay_{ns.case}.hex"
    rfile.write_text("".join(f"{w:018X}\n" for w in rep), encoding="ascii", newline="\n")

    vh = REPO / "build" / "e3" / "model_paths.vh"
    if not vh.is_file():                  # first run on a machine: run_e3.py has not written it yet
        import run_e3
        run_e3.write_model_paths(REPO / "build" / "e3" / "vec" / "model", vh)
    model_vh = vh.read_text(encoding="ascii")
    (OUT / "e3c_paths.vh").write_text(
        f"// generated by scripts/sim/gen_e3c.py ({ns.case})\n"
        f"`define E3C_REPLAY_FILE \"{rfile.as_posix()}\"\n"
        f"`define E3C_REPLAY_FRAMES {len(rep)}\n" + model_vh, encoding="ascii", newline="\n")

    dec = words(d / "decisions.hex")
    log = words(d / "logits.hex")
    seg_start = [i for i, f in enumerate(frames) if (f >> 128) & 0x3]
    coef = words(VEC / "model" / "dsp_coef4.hex")
    rows = []
    for k, (dw, lw) in enumerate(zip(dec, log)):
        am, end, seg = dw & 0xF, (dw >> 40) & 0xFFFFFF, (dw >> 64) & 0xFF
        sc = [s32(lw >> (32 * c)) for c in range(6)]
        if ((lw >> 192) & 0xFFFFFF) != end or ((lw >> 216) & 0xFF) != seg:
            sys.exit(f"decision {k}: logits/decisions disagree")
        rows.append((sc, am, end, seg, seg_start[seg] + end))
    lines = [
        "/* e3c_expected.h - GENERATED by scripts/sim/gen_e3c.py from the E2 golden vectors",
        f" * (build/e3/vec/{ns.case}; model: E2 reference fold subject 1, P2 test day 3, seed 0).",
        " * Do not edit. Expected CNN results of the replayed stream and the DSP coefficients. */",
        "#ifndef E3C_EXPECTED_H", "#define E3C_EXPECTED_H", "", "#include <stdint.h>", "",
        f"#define E3C_NFRAMES {len(frames)}", f"#define E3C_NRES {len(rows)}", f"#define E3C_NSEG {len(seg_start)}", "",
        "typedef struct { int32_t score[6]; uint32_t argmax, end, seg, fidx; } e3c_result_t;", "",
        "static const e3c_result_t e3c_expected[E3C_NRES] = {"]
    for sc, am, end, seg, fidx in rows:
        lines.append("    {{" + ", ".join(str(s) for s in sc) + f"}}, {am}, {end}, {seg}, {fidx}}},")
    lines += ["};", "", "/* Q2.16 coefficients, slot*5 + {b0, b1, b2, a1, a2}; slots DC, notch, BP0, BP1 */",
              "static const int32_t e3c_dsp_coef[20] = {",
              "    " + ", ".join(str(c - (1 << 18) if c & (1 << 17) else c) for c in coef) + "};", "",
              "#endif", ""]
    HDR.parent.mkdir(parents=True, exist_ok=True)
    HDR.write_text("\n".join(lines), encoding="ascii", newline="\n")
    print(f"{ns.case}: {len(frames)} frames, {len(rows)} results -> {rfile.relative_to(REPO)}, "
          f"{HDR.relative_to(REPO)}, build/e3c/e3c_paths.vh")
    return 0


if __name__ == "__main__":
    sys.exit(main())
